/**
 * Recognising one of our own mails coming back, on a transport that does not let
 * us keep our own `Message-ID`.
 *
 * The old test of authorship was the host on the `Message-ID`: we minted the id,
 * so the host was a domain we operate. A provider that assigns its own id ends
 * that — the host on the wire is the provider's, shared with every other account
 * on the region, and it proves nothing about who sent the message. What is left
 * that we still control is the reply address we put on the mail ourselves: it
 * carries this workspace's label and an HMAC tag over it, so nobody who has not
 * received one of our mails can write one down.
 *
 * The predicate is the REAL one from the address grammar and the fixtures are
 * minted by the REAL minter, so these tests fail if the two sides ever stop
 * agreeing — which a hand-written fake predicate could never notice.
 */
describe('mailLoopSignal', () => {
  const ENV = {
    EMAIL_INBOUND_DOMAIN: 'tenaevexeo.resend.app',
    EMAIL_INBOUND_SIGNING_SECRET: 'whsec_dGVzdHNlY3JldA==',
  }
  const SLUG = 'ws-t1'
  const CONVERSATION_ID = 'conversation_01kw8qxn1eeh4t2rek7varh032' as ConversationId
  /** The addresses this install mints and puts on its own outbound mail. */
  const OUR_REPLY_TO = inboundReplyToAddress(CONVERSATION_ID, SLUG, ENV)!
  /** The domains whose `Message-ID` host we mint ourselves. */
  const OUR_DOMAINS = new Set(['tenaevexeo.resend.app', 'acme.example'])
  /** The question the ingest core asks, wired exactly as it wires it. */
  const ours = (address: string) => isOwnInboundAddress(address, SLUG, ENV)

  /**
   * An id in the shape the sending provider assigns: its own opaque local part
   * at a host shared by every account on the region. Both of our own mail and of
   * every stranger's, which is the whole point.
   */
  const providerId = (local: string) => `<${local}@email.amazonses.com>`

  const message = (over: Partial<ParsedInboundEmail>): ParsedInboundEmail => ({
    toAddresses: [],
    ccAddresses: [],
    replyToAddresses: [],
    from: 'jane@example.com',
    subject: 'Re: your message',
    text: 'hi',
    messageId: null,
    emailId: null,
    inReplyTo: null,
    references: [],
    autoSubmitted: null,
    autoResponseSuppress: null,
    precedence: null,
    hasListHeaders: false,
    authenticationResults: null,
    ...over,
  })

  it('names the reply address when our own mail returns without our Message-ID', () => {
    const ourMailComingBack = message({
      from: 'Support <noreply@acme.example>',
      messageId: providerId('0100019a1f4c8e21-6b2d'),
      toAddresses: ['jane@example.com'],
      replyToAddresses: [OUR_REPLY_TO],
    })
    // WHICH signal, not merely that there was one: this one is an inference
    // about a header the sender controls, and the ingest core retains what it
    // infers and suppresses only what it can prove.
    expect(mailLoopSignal(ourMailComingBack, OUR_DOMAINS, ours)).toBe('own_reply_to')
  })

  it('does not claim a different account’s mail that shares the provider’s Message-ID host', () => {
    // THE decisive case. This message is exactly what "add amazonses.com to the
    // set of hosts that mean ours" would swallow: a real customer writing in,
    // whose own mail happens to leave through the same provider and region as
    // ours, so its Message-ID host is character-for-character the one on our own
    // mail. Nothing about it is ours.
    const strangerViaSameProvider = message({
      from: 'Billing <billing@other-company.example>',
      messageId: providerId('0100019a1f4c8e21-9f04'),
      toAddresses: [OUR_REPLY_TO],
      replyToAddresses: ['billing@other-company.example'],
      text: 'Our invoice did not arrive, can you check?',
    })
    expect(mailLoopSignal(strangerViaSameProvider, OUR_DOMAINS, ours)).toBeNull()
    expect(isAutoGeneratedEmail(strangerViaSameProvider, OUR_DOMAINS)).toBe(false)
  })

  it('does not claim a reply merely for being ADDRESSED to an address we minted', () => {
    // Every genuine reply carries our address — in `To`, because that is where
    // we asked it to be sent. Reading the recipients instead of the reply
    // address would suppress the entire inbound channel, which is why the
    // question is asked of `Reply-To` alone.
    const genuineReply = message({
      from: 'Jane <jane@example.com>',
      messageId: providerId('0100019a1f4c8e21-aa11'),
      toAddresses: [OUR_REPLY_TO],
      ccAddresses: [OUR_REPLY_TO],
      replyToAddresses: [],
    })
    expect(mailLoopSignal(genuineReply, OUR_DOMAINS, ours)).toBeNull()
  })

  it('does not claim a reply whose sender set a Reply-To of their own', () => {
    const replyWithOwnReplyTo = message({
      from: 'Jane <jane@example.com>',
      messageId: '<x@example.com>',
      toAddresses: [OUR_REPLY_TO],
      replyToAddresses: ['Jane at work <jane@work.example>'],
    })
    expect(mailLoopSignal(replyWithOwnReplyTo, OUR_DOMAINS, ours)).toBeNull()
  })

  it('does not accept a Reply-To shaped like ours whose tag was forged', () => {
    const local = OUR_REPLY_TO.slice(0, OUR_REPLY_TO.indexOf('@'))
    const tag = local.slice(local.lastIndexOf('.') + 1)
    const forged = OUR_REPLY_TO.replace(tag, `${tag[0] === 'A' ? 'B' : 'A'}${tag.slice(1)}`)
    // Identical to ours everywhere a shape test can look; only the tag's value
    // differs, so only the HMAC separates them.
    expect(forged).not.toBe(OUR_REPLY_TO)
    expect(forged.length).toBe(OUR_REPLY_TO.length)
    expect(mailLoopSignal(message({ replyToAddresses: [forged] }), OUR_DOMAINS, ours)).toBeNull()
  })

  it('does not accept a neighbouring workspace’s reply address on the same fleet', () => {
    const neighbour = inboundReplyToAddress(CONVERSATION_ID, 'ws-t2', ENV)!
    expect(mailLoopSignal(message({ replyToAddresses: [neighbour] }), OUR_DOMAINS, ours)).toBeNull()
  })

  it('still names the Message-ID on the rung where we mint the id ourselves', () => {
    // SMTP and the console rung both keep the header we set, so the domain test
    // is still the whole answer there. Adding the reply-address signal must not
    // cost a self-hoster the guard they already had — and this signal IS a fact
    // about that install, so it keeps the suppression the other one gives up.
    const smtpLoop = message({
      messageId: '<c.01kw8qxn1eeh4t2rek7varh032.n1@acme.example>',
      replyToAddresses: [],
    })
    expect(mailLoopSignal(smtpLoop, OUR_DOMAINS, ours)).toBe('own_message_id')
    expect(isAutoGeneratedEmail(smtpLoop, OUR_DOMAINS)).toBe(true)
  })

  it('reports the reply address when a message answers both, so it is retained', () => {
    // Order is a disposition, not a preference: this message is refused either
    // way, and reporting the inference is what keeps a copy of it.
    const both = message({
      messageId: '<c.01kw8qxn1eeh4t2rek7varh032.n1@acme.example>',
      replyToAddresses: [OUR_REPLY_TO],
    })
    expect(mailLoopSignal(both, OUR_DOMAINS, ours)).toBe('own_reply_to')
  })

  it('answers "not ours" when the signal is absent, which is the safe direction', () => {
    // Absent means ingested, never refused. Getting this wrong in the other
    // direction costs a customer their message; getting it wrong in this
    // direction files one the other auto-mail guards (RFC 3834, Precedence,
    // List-*) and the dedupe key still stand behind.
    const noSignal = message({
      messageId: providerId('0100019a1f4c8e21-bb22'),
      replyToAddresses: [],
    })
    expect(mailLoopSignal(noSignal, OUR_DOMAINS, ours)).toBeNull()
    // And with no predicate wired at all, our own mail coming back is likewise
    // ingested rather than refused.
    const ourMailComingBack = message({
      messageId: providerId('0100019a1f4c8e21-6b2d'),
      replyToAddresses: [OUR_REPLY_TO],
    })
    expect(mailLoopSignal(ourMailComingBack, OUR_DOMAINS)).toBeNull()
  })
})

describe('extractReplyText', () => {
  it('drops a Gmail-style quoted history below "On … wrote:"', () => {
    const raw = [
      'This is my reply.',
      '',
      'On Mon, Jun 1, 2026 at 9:00 AM Support <reply+x@d> wrote:',
      '> previous agent message',
      '> more quoted text',
    ].join('\n')
    expect(extractReplyText(raw)).toBe('This is my reply.')
  })

  it('drops a leading-`>` quoted block with no separator line', () => {
    const raw = ['My answer is here.', '> quoted', '> quoted 2'].join('\n')
    expect(extractReplyText(raw)).toBe('My answer is here.')
  })

  it('strips a trailing signature after the "-- " delimiter', () => {
    const raw = ['Sounds good.', '', '-- ', 'Jane Visitor', 'Acme Inc'].join('\n')
    expect(extractReplyText(raw)).toBe('Sounds good.')
  })

  it('leaves a plain reply untouched (trimmed)', () => {
    expect(extractReplyText('  just a normal reply  ')).toBe('just a normal reply')
  })

  it('keeps a reply that begins with a "From:" prose line (not a forwarded header)', () => {
    expect(extractReplyText('From: my perspective this is broken\nplease help')).toBe(
      'From: my perspective this is broken\nplease help'
    )
  })

  it('keeps prose that merely contains a mid-body "From:" line', () => {
    const raw = 'I have two questions.\n\nFrom: the docs it says X\nCan you clarify?'
    expect(extractReplyText(raw)).toBe(raw)
  })

  it('falls back to the visitor text when a quote separator lands on the first line', () => {
    // Some clients put the attribution line first; cutting at it would drop the
    // whole message, so we recover the non-quoted text instead of returning "".
    expect(extractReplyText('On Mon, Jun 1, 2026 someone wrote:\nThanks, this is fixed now!')).toBe(
      'Thanks, this is fixed now!'
    )
  })

  it('still returns empty for a reply that is entirely quoted history', () => {
    expect(extractReplyText('On Mon wrote:\n> only quoted text\n> more quoted')).toBe('')
  })
})

