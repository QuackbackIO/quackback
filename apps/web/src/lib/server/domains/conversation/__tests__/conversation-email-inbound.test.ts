describe('inboundDedupeKey', () => {
  // No cast. A fixture asserted into the type compiles whatever the type later
  // requires, so the next field the ingest path depends on would be missing here
  // and nothing would say so — which is how a producer ends up feeding the
  // system a message shape the system does not actually accept.
  const parsed = (over: Partial<ParsedInboundEmail>): ParsedInboundEmail => ({
    toAddresses: [],
    ccAddresses: [],
    replyToAddresses: [],
    from: 'someone@example.com',
    subject: null,
    text: '',
    messageId: null,
    emailId: null,
    inReplyTo: null,
    references: [],
    autoSubmitted: null,
    autoResponseSuppress: null,
    precedence: null,
    hasListHeaders: false,
    authenticationResults: null,
    ...over,
  })

  it('is the message’s own id, unchanged and unprefixed', () => {
    // Every row ingested before the fallback existed is filed under this exact
    // value, so re-spelling it would make today's copy of a redelivered message
    // fail to match yesterday's row.
    expect(inboundDedupeKey(parsed({ messageId: '<m-1@example.com>' }))).toBe('<m-1@example.com>')
  })

  it('falls back to the transport id, namespaced, and only when there is no Message-ID', () => {
    expect(inboundDedupeKey(parsed({ transportMessageId: 'ses-1' }))).toBe('qb-transport:ses-1')
    expect(
      inboundDedupeKey(parsed({ messageId: '<m-1@example.com>', transportMessageId: 'ses-1' }))
    ).toBe('<m-1@example.com>')
    expect(inboundDedupeKey(parsed({}))).toBeNull()
    expect(inboundDedupeKey(parsed({ transportMessageId: '   ' }))).toBeNull()
  })

  it('caps BOTH kinds of id, because both land in one index', () => {
    // The cap belongs to the key, not to either source of one. A `Message-ID`
    // arrives in a header nobody upstream bounds; capping only the transport id
    // our own sender sets would leave the exposed one uncapped in the same
    // unique index, where an oversized entry is not a bad dedupe key but an
    // INSERT that throws.
    const atCeiling = `<${'x'.repeat(MAX_DEDUPE_KEY_CHARS - 2)}>`
    expect(atCeiling.length).toBe(MAX_DEDUPE_KEY_CHARS)
    expect(inboundDedupeKey(parsed({ messageId: atCeiling }))).toBe(atCeiling)
    expect(inboundDedupeKey(parsed({ messageId: `${atCeiling}x` }))).toBeNull()

    const transportAtCeiling = 'x'.repeat(MAX_TRANSPORT_MESSAGE_ID_CHARS)
    expect(inboundDedupeKey(parsed({ transportMessageId: transportAtCeiling }))).toHaveLength(
      MAX_DEDUPE_KEY_CHARS
    )
    expect(inboundDedupeKey(parsed({ transportMessageId: `${transportAtCeiling}x` }))).toBeNull()
  })

  it('drops an over-long id rather than truncating it', () => {
    // Truncation would be worse than the throw it avoids: two distinct long ids
    // would truncate to one key, and the second message would be silently
    // suppressed as a duplicate of a message it has nothing to do with.
    const long = (tail: string) => `<${'x'.repeat(MAX_DEDUPE_KEY_CHARS)}${tail}@example.com>`
    expect(inboundDedupeKey(parsed({ messageId: long('a') }))).toBeNull()
    expect(inboundDedupeKey(parsed({ messageId: long('b') }))).toBeNull()
  })
})

